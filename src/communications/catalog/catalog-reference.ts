/**
 * B0-MSG-06 — the notification catalogue reference, generated from
 * `COMMUNICATION_CATALOG` so the documentation cannot drift from the code.
 *
 * `npm run docs:communication-catalog` writes it to
 * `docs/communications/COMMUNICATION_CATALOG_REFERENCE.md`, and
 * `catalog-reference.spec.ts` fails when that file is out of date.
 */
import {
  COMMUNICATION_CATALOG,
  type CommunicationCatalogEntry,
} from './communication-catalog';

/** Where the generated reference lives, relative to the repository root. */
export const CATALOG_REFERENCE_PATH =
  'docs/communications/COMMUNICATION_CATALOG_REFERENCE.md';

/**
 * Events whose feature customers cannot use yet. They stay in the table,
 * marked, and are left out of any public list (DOC-REF-005).
 */
const NOT_LAUNCHED: readonly {
  readonly match: (key: string) => boolean;
  readonly reason: string;
}[] = [
  {
    match: (key) => key.startsWith('live_session.') || key.startsWith('live_provider.'),
    reason: 'Live Sessions add-on not launched',
  },
  {
    match: (key) => key.startsWith('retention.video.'),
    reason: 'hosted video cannot be authored yet',
  },
  {
    match: (key) =>
      key === 'course.order.paid' ||
      key === 'course.order.payment_failed' ||
      key === 'course.order.refunded',
    reason: 'Atlas Payments (gateway checkout) not launched',
  },
];

export function notLaunchedReason(key: string): string | null {
  return NOT_LAUNCHED.find((rule) => rule.match(key))?.reason ?? null;
}

const cell = (value: string): string => value.replace(/\|/g, '\\|');

export function renderCatalogReference(
  catalog: Readonly<Record<string, CommunicationCatalogEntry>> = COMMUNICATION_CATALOG,
): string {
  const rows = Object.entries(catalog).sort(
    ([a, x], [b, y]) => x.category.localeCompare(y.category) || a.localeCompare(b),
  );
  const notLaunched = rows.filter(([key]) => notLaunchedReason(key) !== null).length;
  const lines = [
    '# Notification catalogue reference',
    '',
    '<!-- GENERATED by `npm run docs:communication-catalog` from',
    '     src/communications/catalog/communication-catalog.ts — do not edit by hand. -->',
    '',
    `**${rows.length} events** in the catalogue, of which **${rows.length - notLaunched} are launched** ` +
      `and ${notLaunched} belong to a feature customers cannot use yet (marked below; leave them out of any public list).`,
    '',
    "In-app and Email are the catalogue's channel policies (`CommunicationInAppPolicy`, " +
      '`CommunicationEmailPolicy` in communication-catalog.ts); Branding is whose brand and host the email uses.',
    '',
    '| Key | Category | Audience | In-app | Email | Branding | Launched |',
    '|---|---|---|---|---|---|---|',
    ...rows.map(([key, entry]) => {
      const reason = notLaunchedReason(key);
      return `| \`${cell(key)}\` | ${entry.category} | ${entry.audience} | ${entry.channels.inApp} | ${entry.channels.email} | ${entry.branding} | ${reason ? `No — ${cell(reason)}` : 'Yes'} |`;
    }),
    '',
  ];
  return lines.join('\n');
}
