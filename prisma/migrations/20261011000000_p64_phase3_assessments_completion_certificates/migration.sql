-- The deadline sweep runs with no tenant or user context (it is the
-- system acting on its own behalf), so it cannot see `quiz_attempts`
-- through any policy. This definer returns only the ids the sweep needs;
-- each attempt is then finalised under ITS OWN student's context, so the
-- write path stays inside the self policies. Grace of 30 s matches
-- `QUIZ_SUBMIT_GRACE_SECONDS` in the engine.
CREATE OR REPLACE FUNCTION find_due_quiz_attempts(p_limit integer)
RETURNS TABLE ("id" text, "student_id" text, "deadline_at" timestamp(3))
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT a."id", a."student_id", a."deadline_at"
  FROM "quiz_attempts" a
  WHERE a."status" = 'in_progress'
    AND a."deadline_at" IS NOT NULL
    AND a."deadline_at" + interval '30 seconds' < now()
  ORDER BY a."deadline_at" ASC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 100), 1), 500);
$$;

-- Serial allocation is atomic (single UPSERT) and refuses to allocate for
-- an academy outside the caller's tenant context: the function is a
-- definer, so the check is what keeps it honest.
CREATE OR REPLACE FUNCTION next_certificate_serial(p_academy_id text, p_year integer)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_org text;
  v_value integer;
BEGIN
  SELECT a."organization_id" INTO v_org FROM "academies" a WHERE a."id" = p_academy_id;
  IF v_org IS NULL OR v_org <> current_setting('app.current_organization_id', true) THEN
    RAISE EXCEPTION 'certificate serial allocation refused for academy %', p_academy_id
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  INSERT INTO "certificate_serial_counters" ("academy_id", "year", "next_value")
  VALUES (p_academy_id, p_year, 2)
  ON CONFLICT ("academy_id", "year")
  DO UPDATE SET "next_value" = "certificate_serial_counters"."next_value" + 1
  RETURNING "next_value" - 1 INTO v_value;
  RETURN v_value;
END;
$$;

-- Public verification: returns ONLY the fields the plan allows a stranger
-- to see (issued-to, course, academy, date, status) and never the
-- snapshot's score, email or instructors. Uniform shape for issued and
-- revoked; unknown codes return no row and the API pads its timing.
CREATE OR REPLACE FUNCTION verify_certificate(p_code text)
RETURNS TABLE (
  "serial" text,
  "status" "certificate_state",
  "issued_to" text,
  "course_title" text,
  "academy_name" text,
  "academy_slug" text,
  "academy_id" text,
  "issued_at" timestamp(3),
  "completed_at" text,
  "revoked_at" timestamp(3),
  "version" integer
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    c."serial",
    c."status",
    c."snapshot"->>'learnerName',
    c."snapshot"->>'courseTitle',
    c."snapshot"->>'academyName',
    a."slug",
    c."academy_id",
    c."issued_at",
    c."snapshot"->>'completedAt',
    c."revoked_at",
    c."version"
  FROM "certificates" c
  JOIN "academies" a ON a."id" = c."academy_id"
  WHERE c."verification_code" = upper(regexp_replace(p_code, '[^A-Za-z0-9]', '', 'g'))
  LIMIT 1;
$$;

