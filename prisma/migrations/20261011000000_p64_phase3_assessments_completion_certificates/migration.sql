-- course_progress: certificate issuance runs in the academy's tenant
-- context (never as the learner — a learner must not be the principal
-- that writes their own certificate state), so the tenant tier gains
-- UPDATE. Scope identical to the existing tenant SELECT.
CREATE POLICY "course_progress_tenant_update" ON "course_progress"
  FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM "enrollments" e
      JOIN "academies" a ON a."id" = e."academy_id"
      WHERE e."id" = "course_progress"."enrollment_id"
        AND a."organization_id"::text = current_setting('app.current_organization_id', true)
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM "enrollments" e
      JOIN "academies" a ON a."id" = e."academy_id"
      WHERE e."id" = "course_progress"."enrollment_id"
        AND a."organization_id"::text = current_setting('app.current_organization_id', true)
    )
  );
